// Real component handlers: fixed actions, modal confirmation and native status retries.
const assert = require('node:assert/strict');
const { harness } = require('./video_components_test_dom.cjs');
const { context, byId, cards, timers, requests } = harness();
const primary = cards.get('rife').children[0], secondary = cards.get('rife').children[1];
const dialog = byId('component-dialog'), label = byId('settings-frame-interpolation-status');
const render = (component, fields = {}) => context.updateFrameInterpolationStatus({ componentStatus: 'unavailable', component, ...fields });
render({ installed: false });
assert.equal(primary.disabled, false); assert.equal(secondary.disabled, true);
render({ installed: false, busy: true, progress: { phase: 'downloading', downloadedBytes: 5, totalBytes: 9, source: 'GitHub' } });
assert.equal(primary.dataset.busy, 'true'); assert.equal(timers.size, 1); assert.match(label.textContent, /5 B \/ 9 B/);
render({ installed: false, restartRequired: true, pendingOperation: 'install' });
assert.equal(primary.disabled, false); assert.equal(primary.textContent, '重启生效'); assert.equal(secondary.textContent, '取消安装');
assert.equal(dialog.open, undefined, 'completed install does not interrupt the page with an automatic prompt');
assert.equal(requests.length, 0, 'no restart without confirmation');
context.showComponentDialog('rife', 'restart', primary);
assert.equal(dialog.open, true); context.closeComponentDialog();
render({ installed: false, restartRequired: true, pendingOperation: 'install' });
assert.equal(dialog.open, false, 'later stays respected during polling');
context.showComponentDialog('rife', 'restart', primary);
render({ installed: false, restartRequired: true, pendingOperation: 'install' }, { failureCode: 'frame_interpolation_component_invalid', failureDetail: 'payload damaged' });
assert.equal(primary.disabled, true); assert.equal(secondary.disabled, false); assert.equal(dialog.open, false); assert.match(label.textContent, /payload damaged/);
render({ installed: true, restartRequired: true, pendingOperation: 'uninstall' });
assert.equal(primary.textContent, '等待重启'); assert.equal(primary.disabled, true); assert.equal(secondary.disabled, true);
render({ installed: true }, { componentStatus: 'ready', models: [{}, {}, {}], gpuName: 'RTX' });
assert.equal(primary.textContent, '已安装'); assert.equal(primary.dataset.busy, 'false'); assert.equal(secondary.disabled, false);
assert.equal(byId('player-interpolation').dataset.componentReady, 'true');
assert.equal(cards.get('rife').children.length, 2);
let failure, response;
context.nativeRequest = async (...args) => { requests.push(args); if (failure) throw failure; return response; };
async function tick() { assert.equal(timers.size, 1); const [id, task] = timers.entries().next().value; timers.delete(id); await task.fn(); }
async function main() {
    render({ installed: false });
    response = { components: [], component: { installed: false, busy: true, progress: { phase: 'selecting' } } };
    context.showComponentDialog('rife', 'install', primary);
    assert.equal(requests.length, 0, 'choosing an installation source does not start installation');
    await context.confirmComponentDialog(true);
    assert.equal(requests[0][1], 'video_component_import');
    assert.deepEqual(Array.from(requests[0][2]), ['video_component_import', 'rife']);
    assert.equal(requests[1][1], 'frame_interpolation_status');
    assert.equal(primary.disabled, true); assert.match(label.textContent, /请选择本地/);
    render({ installed: false });
    response = { components: [], component: { installed: false, restartRequired: true, pendingOperation: 'install' } };
    context.showComponentDialog('rife', 'install', primary);
    await context.confirmComponentDialog();
    assert.equal(requests.at(-2)[1], 'video_component_install');
    assert.equal(primary.textContent, '重启生效');
    response = { components: [], component: { installed: false } };
    await context.changeVideoComponent('rife', 'cancel');
    assert.equal(requests.at(-2)[1], 'video_component_cancel'); assert.equal(primary.disabled, false);
    render({ installed: true }, { componentStatus: 'ready' });
    response = { components: [], component: { installed: true, restartRequired: true, pendingOperation: 'uninstall' } };
    context.showComponentDialog('rife', 'uninstall', secondary);
    await context.confirmComponentDialog();
    assert.equal(requests.at(-2)[1], 'video_component_uninstall'); assert.equal(primary.textContent, '等待重启');
    render({ installed: false, busy: true }); failure = new Error('transient IPC timeout');
    await tick(); assert.equal(timers.size, 1); assert.equal([...timers.values()][0].delay, 3000); assert.match(label.textContent, /正在重新查询/);
    await tick(); assert.equal(timers.size, 1, 'status failure does not multiply timers');
    failure = null; response = { component: { installed: false, restartRequired: true, pendingOperation: 'install' } };
    await tick(); assert.equal(timers.size, 0);
    context.showComponentDialog('rife', 'restart', primary); context.closeComponentDialog();
    failure = new Error('restart helper missing'); const before = requests.length;
    await context.changeVideoComponent('rife', 'restart');
    assert.equal(requests[before][1], 'video_component_restart'); assert.equal(requests[before][2][1], 'rife');
    assert.equal(requests.length, before + 2); assert.match(label.textContent, /不会自动重复重启/);
    failure = null; await context.refreshFrameInterpolationStatus();
    response = { restarting: true }; const count = requests.length;
    await context.changeVideoComponent('rife', 'restart'); await context.changeVideoComponent('rife', 'restart');
    assert.equal(requests.length, count + 1, 'double click sends one restart');
    render({ installed: false, restartRequired: true, pendingOperation: 'install' });
    assert.equal(primary.disabled, true, 'late status cannot re-enable controls while restarting');
    console.log('RIFE_COMPONENT_UI_TEST_OK fixed-actions/installed-not-busy/modal/later/damaged-pending/status-retry/restart-failure/single-restart');
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
